def _generate_uuid() -> str:
    """Generate a UUID4 string."""
    return str(uuid.uuid4())


def _now_ms() -> int:
    """Return current epoch time in milliseconds."""
    return int(time.time() * 1000)


def compute_sha256(file_path: str) -> str:
    """Compute the SHA‑256 hash of a file's contents."""
    h = hashlib.sha256()
    with open(file_path, "rb") as f:
        for chunk in iter(lambda: f.read(8192), b""):
            h.update(chunk)
    return h.hexdigest()


class RunStatus(str, Enum):
    """Lifecycle status of a Run."""

    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"


class PermissionProfile(str, Enum):
    """Permission handling strategy for a Project."""

    ASK = "ask"
    AUTO = "auto"
    FULL = "full"


class ArtifactKind(str, Enum):
    """Classification of an artifact."""

    WORKSPACE = "workspace"
    GENERATED = "generated"
    EXTERNAL = "external"


@dataclass
class Project:
    """A research project grouping runs and permission defaults."""

    id: str
    name: str
    description: str = ""
    createdAt: int = field(default_factory=_now_ms)
    updatedAt: int = field(default_factory=_now_ms)
    defaultPermission: PermissionProfile = PermissionProfile.ASK

    def to_dict(self) -> Dict[str, Any]:
        """Serialize the project to a plain dict."""
        return asdict(self)


@dataclass
class Run:
    """A single execution of a research task."""

    id: str
    projectId: str
    status: RunStatus = RunStatus.RUNNING
    startedAt: int = field(default_factory=_now_ms)
    completedAt: Optional[int] = None
    artifactIds: List[str] = field(default_factory=list)
    log: str = ""

    def start(self) -> None:
        """Mark the run as started and record timestamp."""
        self.status = RunStatus.RUNNING
        self.startedAt = _now_ms()
        self.append_log("Run started")

    def complete(self) -> None:
        """Mark the run as completed and record timestamp."""
        self.status = RunStatus.COMPLETED
        self.completedAt = _now_ms()
        self.append_log("Run completed")

    def fail(self, reason: str) -> None:
        """Mark the run as failed, record timestamp and reason."""
        self.status = RunStatus.FAILED
        self.completedAt = _now_ms()
        self.append_log(f"Run failed: {reason}")

    def add_artifact(self, artifact_id: str) -> None:
        """Register an artifact ID with this run."""
        self.artifactIds.append(artifact_id)
        self.append_log(f"Artifact registered: {artifact_id}")

    def append_log(self, entry: str) -> None:
        """Append a line to the run log with a timestamp."""
        ts = time.strftime("%Y-%m-%d %H:%M:%S", time.localtime())
        self.log += f"[{ts}] {entry}\n"


@dataclass
class Artifact:
    """Immutable representation of a file produced by a kernel step."""

    id: str
    runId: str
    kind: ArtifactKind
    path: str
    sha256: str
    size: int
    mimeType: str
    createdAt: int = field(default_factory=_now_ms)

    @classmethod
    def create_from_file(
        cls, run_id: str, kind: ArtifactKind, file_path: str, mime_type: Optional[str] = None
    ) -> "Artifact":
        """Create an Artifact instance from a file on disk."""
        p = Path(file_path).resolve()
        if not p.is_file():
            raise FileNotFoundError(f"Artifact file not found: {file_path}")

        size = p.stat().st_size
        sha256 = compute_sha256(str(p))
        inferred_mime = mime_type or mimetypes.guess_type(str(p))[0] or "application/octet-stream"

        return cls(
            id=_generate_uuid(),
            runId=run_id,
            kind=kind,
            path=str(p),
            sha256=sha256,
            size=size,
            mimeType=inferred_mime,
        )

    def to_dict(self) -> Dict[str, Any]:
        """Serialize the artifact to a plain dict."""
        return asdict(self)


@dataclass
class PlanStep:
    """A single step in a plan generated by a provider."""

    name: str
    args: Dict[str, Any]

    def to_json(self) -> str:
        """Serialize the step to JSON."""
        return json.dumps({"name": self.name, "args": self.args})


@dataclass
class ExecutionMetadata:
    """Metadata returned after executing a kernel step."""

    step_index: int
    stdout: str
    stderr: str
    exit_code: int
    usage: Dict[str, Any]
    output_dir: str

    def succeeded(self) -> bool:
        """Return True if the step exited with code 0."""
        return self.exit_code == 0


