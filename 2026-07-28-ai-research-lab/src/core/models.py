class ArtifactStore:
    """SQLite‑backed immutable store for projects, runs, and artifacts."""

    def __init__(self, db_path: str):
        self.db_path = db_path
        self.conn = sqlite3.connect(self.db_path, check_same_thread=False)
        self._ensure_schema()

    def _ensure_schema(self) -> None:
        cur = self.conn.cursor()
        cur.executescript(
            """
            CREATE TABLE IF NOT EXISTS projects (
                id TEXT PRIMARY KEY,
                name TEXT NOT NULL,
                description TEXT,
                createdAt INTEGER,
                updatedAt INTEGER,
                defaultPermission TEXT
            );
            CREATE TABLE IF NOT EXISTS runs (
                id TEXT PRIMARY KEY,
                projectId TEXT NOT NULL,
                status TEXT,
                startedAt INTEGER,
                completedAt INTEGER,
                artifactIds TEXT,
                log TEXT,
                FOREIGN KEY(projectId) REFERENCES projects(id)
            );
            CREATE TABLE IF NOT EXISTS artifacts (
                id TEXT PRIMARY KEY,
                runId TEXT NOT NULL,
                kind TEXT,
                path TEXT,
                sha256 TEXT,
                size INTEGER,
                mimeType TEXT,
                createdAt INTEGER,
                FOREIGN KEY(runId) REFERENCES runs(id)
            );
            """
        )
        self.conn.commit()

    def save_project(self, project: Project) -> None:
        cur = self.conn.cursor()
        cur.execute(
            """
            INSERT OR REPLACE INTO projects (id, name, description, createdAt, updatedAt, defaultPermission)
            VALUES (?, ?, ?, ?, ?, ?)
            """,
            (
                project.id,
                project.name,
                project.description,
                project.createdAt,
                project.updatedAt,
                project.defaultPermission.value,
            ),
        )
        self.conn.commit()

    def save_run(self, run: Run) -> None:
        cur = self.conn.cursor()
        cur.execute(
            """
            INSERT OR REPLACE INTO runs (id, projectId, status, startedAt, completedAt, artifactIds, log)
            VALUES (?, ?, ?, ?, ?, ?, ?)
            """,
            (
                run.id,
                run.projectId,
                run.status.value,
                run.startedAt,
                run.completedAt,
                json.dumps(run.artifactIds),
                run.log,
            ),
        )
        self.conn.commit()

    def save_artifact(self, artifact: Artifact) -> None:
        cur = self.conn.cursor()
        cur.execute(
            """
            INSERT OR REPLACE INTO artifacts (id, runId, kind, path, sha256, size, mimeType, createdAt)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                artifact.id,
                artifact.runId,
                artifact.kind.value,
                artifact.path,
                artifact.sha256,
                artifact.size,
                artifact.mimeType,
                artifact.createdAt,
            ),
        )
        self.conn.commit()

    def get_run(self, run_id: str) -> Optional[Run]:
        cur = self.conn.cursor()
        cur.execute("SELECT * FROM runs WHERE id = ?", (run_id,))
        row = cur.fetchone()
        if not row:
            return None
        (
            _id,
            projectId,
            status,
            startedAt,
            completedAt,
            artifactIds_json,
            log,
        ) = row
        return Run(
            id=_id,
            projectId=projectId,
            status=RunStatus(status),
            startedAt=startedAt,
            completedAt=completedAt,
            artifactIds=json.loads(artifactIds_json),
            log=log,
        )

    def list_artifacts_for_run(self, run_id: str) -> List[Artifact]:
        cur = self.conn.cursor()
        cur.execute("SELECT * FROM artifacts WHERE runId = ?", (run_id,))
        rows = cur.fetchall()
        artifacts = []
        for (
            _id,
            _runId,
            kind,
            path,
            sha256,
            size,
            mimeType,
            createdAt,
        ) in rows:
            artifacts.append(
                Artifact(
                    id=_id,
                    runId=_runId,
                    kind=ArtifactKind(kind),
                    path=path,
                    sha256=sha256,
                    size=size,
                    mimeType=mimeType,
                    createdAt=createdAt,
                )
            )
        return artifacts

    def close(self) -> None:
        """Close the underlying SQLite connection."""
        self.conn.close()


